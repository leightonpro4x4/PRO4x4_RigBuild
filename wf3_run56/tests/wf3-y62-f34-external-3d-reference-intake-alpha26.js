 assert.equal(sha(intake.artifacts.board),intake.artifacts.boardSha256);
 const manifest=JSON.parse(fs.readFileSync(path.join(root,intake.artifacts.manifest),'utf8'));
 assert.equal(manifest.intakeId,intake.intakeId);
 assert.equal(manifest.source.url,intake.source.url);
 assert.equal(manifest.rights.productionMeshUseAllowed,false);
 assert.equal(manifest.authenticityAuthority.primary,'owner-supplied 2025 Series 5 Y62 Warrior reference pack');
