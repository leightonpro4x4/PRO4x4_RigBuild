'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const receipt=require('../customer-handoff-receipt.js');
const contract=require('../merged-project-contract.js');
global.window=global;
require('../data-ranger.js');
const data=global.RANGER_DATA;
const bash=data.accessories.find(x=>x.sku==='BP-FRA-NG-22-ASM0');
assert(bash,'Ranger any-of fixture is required');
const snap=contract.buildSnapshot({data,selectedProducts:[bash],lead:{name:'WF1 Receipt',phone:'0400000000'},reference:'P4X4-WF1-RECEIPT',renderResolution:{schemaVersion:'0.22.0',productionReady:false,layers:[{layerId:'base',state:'missing',reason:'approved-master-not-available'}]}});
snap.project={id:'P4X4-PROJ-RECEIPT',revisionId:'R0011',revisionNumber:11,savedAt:'2026-09-13T14:00:00.000Z',source:'merged-sales-queue-submit',projectVersion:11};
const quote=receipt.build(snap,{mode:'quote',queueReference:'P4X4-RANGER-Q-001',workflowStatus:'needs-fitment-review'});
assert.equal(quote.projectId,'P4X4-PROJ-RECEIPT');
assert.equal(quote.revisionId,'R0011');
assert.equal(quote.queueReference,'P4X4-RANGER-Q-001');
assert.equal(quote.customerVisualRule,'REFERENCE_BACKED_APPROVED_VISUALS_ONLY');
assert.equal(quote.visual.fallbackPolicy,'none');
assert.equal(quote.visual.exactMatchRequired,true);
assert.equal(quote.visual.counts.missing,1);
assert.equal(quote.gates.blocking,1,'receipt must preserve exact unresolved OR-dependency state');
assert.ok(quote.verification.some(x=>x.type==='fitment-blocker'&&x.state==='open'));
assert.ok(quote.verification.some(x=>x.type==='visual'&&x.state==='open'));
assert.ok(quote.verification.some(x=>x.type==='staff'&&x.state==='next'));
const share=receipt.build(snap,{mode:'share',share:{revisionId:'R0011',expiresAt:'2026-10-13T14:00:00.000Z',tokenHint:'ABC123'}});
assert.equal(share.share.revisionId,'R0011');
assert.equal(share.mode,'share');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'merged-app.js'),'utf8');
assert.ok(html.indexOf('customer-handoff-receipt.js')<html.indexOf('merged-app.js'),'receipt contract must load before customer runtime');
for(const id of ['handoffReceipt','handoffReceiptTitle','handoffReceiptBody','handoffReceiptReturn','handoffReceiptShare'])assert.match(html,new RegExp(`id="${id}"`));
assert.match(html,/This receipt describes the exact persisted revision shown above/);
assert.match(app,/projectRevision\(state\.projectRecord,state\.revisionId\)\?\.snapshot\|\|review\.snapshot/,'receipt must prefer the exact persisted revision over mutable current state');
assert.match(app,/showHandoffReceipt\(review,result\)/,'successful handoffs must display a receipt');
assert.match(app,/openHandoffReview\('share'\)/,'receipt share action must reuse existing revision-locked share flow');
assert.doesNotMatch(app,/fallbackPolicy\s*:\s*['"]approx/i,'WF1 must never add approximate visual fallback');
console.log('WF1 Alpha 26 immutable handoff receipt / return journey: PASS');
