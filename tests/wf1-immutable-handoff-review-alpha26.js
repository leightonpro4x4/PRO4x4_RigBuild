'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const review=require('../customer-handoff-review.js');
const contract=require('../merged-project-contract.js');
global.window=global;
require('../data-ranger.js');
const data=global.RANGER_DATA;
const bash=data.accessories.find(x=>x.sku==='BP-FRA-NG-22-ASM0');
assert(bash,'Ranger OR-dependency fixture is required');
const draft=contract.buildSnapshot({data,selectedProducts:[bash],lead:{name:'WF1 Review',phone:'0400000000'},reference:'P4X4-WF1-REVIEW',renderResolution:{schemaVersion:'0.22.0',productionReady:false,layers:[{layerId:'base',state:'missing',reason:'hosted-production-proof-required'}]}});
const quoteModel=review.build(draft,{mode:'quote'});
assert.equal(quoteModel.mode,'quote');
assert.equal(quoteModel.revisionState,'pending-immutable-revision');
assert.equal(quoteModel.reference,'P4X4-WF1-REVIEW');
assert.equal(quoteModel.itemCount,1);
assert.equal(quoteModel.gates.blocking.length,1,'unresolved any-of support choice must be visible before quote submission');
assert.equal(quoteModel.gates.blocking[0].type,'dependency-any-of');
assert.equal(quoteModel.visual.productionReady,false);
assert.equal(quoteModel.visual.counts.missing,1);
assert.equal(quoteModel.visual.fallbackPolicy,'none');
assert.equal(quoteModel.visual.exactMatchRequired,true);
assert.equal(quoteModel.customerVisualRule,'REFERENCE_BACKED_APPROVED_VISUALS_ONLY');
assert.ok(Array.isArray(quoteModel.setupChecks));

const saved=JSON.parse(JSON.stringify(draft));
saved.project={id:'P4X4-PROJ-QA',revisionId:'R0007'};
const shareModel=review.build(saved,{mode:'share',projectId:'P4X4-PROJ-QA',revisionId:'R0007'});
assert.equal(shareModel.revisionState,'immutable-saved-revision');
assert.equal(shareModel.projectId,'P4X4-PROJ-QA');
assert.equal(shareModel.revisionId,'R0007');

const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'merged-app.js'),'utf8');
assert.ok(html.indexOf('customer-handoff-review.js')<html.indexOf('merged-app.js'),'review contract must load before configurator runtime');
for(const id of ['handoffReview','handoffReviewTitle','handoffReviewBody','handoffReviewConfirm','handoffReviewCancel'])assert.match(html,new RegExp(`id="${id}"`));
assert.match(html,/Reference-only, master-draft, layer-draft or unsupported visual output is never substituted\./);
assert.match(app,/openHandoffReview\('save'\)/);
assert.match(app,/openHandoffReview\('quote'\)/);
assert.match(app,/openHandoffReview\('share'\)/);
assert.match(app,/snapshotOverride\|\|buildPayload\(\)/,'save must accept the exact captured review snapshot');
assert.match(app,/saveProject\('merged-sales-queue-submit',snapshotOverride\)/,'quote submit must save the reviewed snapshot, not rebuild it');
assert.match(app,/shareBuild\(review\.revisionId\)/,'share must remain pinned to the reviewed immutable revision');
assert.match(app,/revisionId:targetRevision/,'share creation must name the exact reviewed revision');
assert.doesNotMatch(app,/fallbackPolicy\s*:\s*['"]approx/i,'WF1 must not introduce approximate visual fallback');
console.log('WF1 Alpha 26 immutable handoff review: PASS');
