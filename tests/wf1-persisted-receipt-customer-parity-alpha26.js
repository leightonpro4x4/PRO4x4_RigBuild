'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const receipt=require('../customer-handoff-receipt.js');
const contract=require('../merged-project-contract.js');
global.window=global;
require('../data-ranger.js');
const data=global.RANGER_DATA;
const product=data.accessories.find(p=>p.id==='mcc-309bsbk');
assert(product,'governed Ranger fixture must exist');
const lead={name:'Leighton Calvert',phone:'0400 111 222',email:'customer@example.com',postcode:'5014',preferredContact:'email',notes:'Keep the tray clear for touring gear.\nCall before changing any fitment choice.'};
const snapshot=contract.buildSnapshot({data,selectedProducts:[product],lead,reference:'P4X4-WF1-CUSTOMER-PARITY',renderResolution:{productionReady:false,fallbackPolicy:'none',exactMatchRequired:true,layers:[{layerId:'base',state:'missing',reason:'approved-master-not-available'}]}});
snapshot.project={id:'P4X4-PROJ-CUSTOMER',revisionId:'R0022',revisionNumber:22,savedAt:'2026-09-14T06:10:00.000Z',source:'merged-sales-queue-submit',projectVersion:22};
const before=JSON.stringify(snapshot);
const model=receipt.build(snapshot,{mode:'quote',queueReference:'P4X4-Q-R0022',workflowStatus:'needs-fitment-review'});
assert.equal(JSON.stringify(snapshot),before,'receipt customer derivation must not mutate the persisted revision');
assert.equal(model.schemaVersion,'0.26.29');
assert.equal(model.customer.snapshotSource,'persisted-revision.lead');
assert.deepEqual(model.customer,{...lead,snapshotSource:'persisted-revision.lead'});
assert.equal(Object.prototype.hasOwnProperty.call(model.customer,'projectId'),false);
// Receipt model must remain pinned even if caller-owned form/snapshot state changes later.
snapshot.lead.name='CHANGED LATER'; snapshot.lead.phone=''; snapshot.lead.email='changed@example.com'; snapshot.lead.notes='Changed after handoff';
assert.equal(model.customer.name,'Leighton Calvert');
assert.equal(model.customer.phone,'0400 111 222');
assert.equal(model.customer.email,'customer@example.com');
assert.match(model.customer.notes,/tray clear/);
const empty=receipt.build(contract.buildSnapshot({data,selectedProducts:[],lead:{},renderResolution:{productionReady:false,layers:[]}}),{mode:'save'});
assert.equal(empty.customer.name,'');
assert.equal(empty.customer.notes,'');
const root=path.join(__dirname,'..');
const app=fs.readFileSync(path.join(root,'merged-app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'merged.css'),'utf8');
assert.match(app,/function renderReceiptCustomer\(/);
assert.match(app,/CUSTOMER & BUILD NOTES ON THIS REVISION/);
assert.match(app,/persisted-revision\.lead/);
assert.match(app,/Later edits to the quote form do not change this saved receipt\./);
assert.match(app,/\$\{renderReceiptShareAccess\(model,runtime\)\}\$\{renderReceiptVehicleState\(model\)\}\$\{renderReceiptMassCompliance\(model\)\}\$\{renderReceiptCustomer\(model\)\}\$\{renderHandoffVisualLayers/);
const start=app.indexOf('function renderReceiptCustomer('),end=app.indexOf('\nasync function copyHandoffReceiptShare',start);
assert(start>=0&&end>start,'receipt customer render block must exist');
const renderBlock=app.slice(start,end);
assert.doesNotMatch(renderBlock,/leadFromForm\(/,'persisted receipt must never refresh customer data from mutable form state');
assert.doesNotMatch(renderBlock,/saveProject|createBuild|createProjectShare|state\.selected\.(add|delete|clear)/,'customer receipt display must be non-mutating');
assert.match(css,/\.merge-receipt-customer/);
assert.match(css,/\.merge-receipt-build-notes/);
console.log('WF1 Alpha 26 persisted receipt customer/contact + build-notes parity: PASS');
